"""Offline integrity checks for the pinned AgentDojo execution environment.

The published wheel digest and an installed distribution are different byte
representations.  This module never claims that hashing an unpacked
``site-packages`` tree reproduces a wheel SHA.  Instead it supports two honest
verification modes:

* when an operator supplies the published wheel, its archive SHA is checked
  and its immutable payload is compared byte-for-byte with the installation;
* otherwise the installed immutable payload is checked against a canonical
  payload fingerprint frozen from that published wheel.

All checks are local and perform no package resolution or network access.
"""

